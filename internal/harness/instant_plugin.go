package harness

import (
	"encoding/json"
	"errors"
	"net/url"
	"path/filepath"
	"strings"

	"github.com/alekzonder/tariboy/internal/agentdir"
)

// minimumOpenCodeInstantPluginVersion is the oldest opencode that gets the
// instant mail plugin. OpenCode documents no versions for its plugin hooks;
// 1.19.5 is the version the plugin was proven on: a file:// plugin from
// OPENCODE_CONFIG_CONTENT, tool.execute.after with a mutable output.output,
// and Bun.spawn inside the plugin.
const minimumOpenCodeInstantPluginVersion = "1.19.5"

const openCodeInstantPluginFile = "tariboy-instant-mail.js"

// openCodeInstantPlugin runs tmail instant after each successful tool call and
// appends what it prints to the tool result the model reads. OpenCode runs on
// Bun, so the plugin needs no node, bun, jq or python on the agent PATH. It
// spawns nothing without the flag file, and every failure, a 5 s timeout
// included, leaves the tool result unchanged and prints nothing.
const openCodeInstantPlugin = `// Generated by Tariboy. Delivers instant letters into the running iteration.
const TMAIL = %TMAIL%;
const TIMEOUT_MS = 5000;

export const TariboyInstantMail = async () => ({
  "tool.execute.after": async (_input, output) => {
    try {
      const flag = process.env.TARIBOY_INSTANT_MAIL_FLAG;
      if (!flag || typeof output?.output !== "string" || !(await Bun.file(flag).exists())) return;
      const proc = Bun.spawn([TMAIL, "instant", "--format", "opencode-tool-after"], {
        stdin: "ignore", stdout: "pipe", stderr: "ignore",
      });
      let timer;
      const timeout = new Promise((resolve) => {
        timer = setTimeout(() => { proc.kill("SIGKILL"); resolve(null); }, TIMEOUT_MS);
      });
      const result = await Promise.race([Promise.all([new Response(proc.stdout).text(), proc.exited]), timeout]);
      clearTimeout(timer);
      if (result && result[1] === 0 && result[0]) output.output += result[0];
    } catch {}
  },
});
`

// InstantMailHooks returns the OpenCode plugin file. OpenCode loads it from
// the plugin key that the daemon adds to OPENCODE_CONFIG_CONTENT after the
// proxy routing probes, so it needs no argv.
func (opencode) InstantMailHooks(tmail, pluginDir string, _ Config) (InstantMailHooks, error) {
	if !filepath.IsAbs(tmail) || !filepath.IsAbs(pluginDir) {
		return InstantMailHooks{}, errors.New("instant mail hooks need absolute tmail and plugin paths")
	}
	quoted, err := json.Marshal(tmail)
	if err != nil {
		return InstantMailHooks{}, err
	}
	body := strings.Replace(openCodeInstantPlugin, "%TMAIL%", string(quoted), 1)
	return InstantMailHooks{
		Files:          []agentdir.BridgeFile{{Path: openCodeInstantPluginFile, Body: []byte(body), Mode: 0o600}},
		ConfigPlugin:   (&url.URL{Scheme: "file", Path: filepath.Join(pluginDir, openCodeInstantPluginFile)}).String(),
		MinimumVersion: minimumOpenCodeInstantPluginVersion,
	}, nil
}
