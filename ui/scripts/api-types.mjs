// Generates ui/src/lib/api-types.generated.ts from the committed OpenAPI
// snapshot. `--check` compares instead of writing, so frontend-check never
// dirties the tree. `--out PATH` picks another target file (used by tests).
import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const ui = path.resolve(import.meta.dirname, "..");
const spec = path.resolve(ui, "../internal/commands/testdata/openapi.json");
const target = "src/lib/api-types.generated.ts";
const header =
  "// Generated by npm run api-types from internal/commands/testdata/openapi.json. Do not edit.\n\n";

function generate() {
  const raw = execFileSync(
    path.join(ui, "tools/api-types/node_modules/.bin/openapi-typescript"),
    [spec, "--root-types", "--root-types-no-schema-prefix", "--empty-objects-unknown"],
    { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"], maxBuffer: 64 << 20 },
  );
  return execFileSync(
    path.join(ui, "node_modules/.bin/oxfmt"),
    ["-c", path.join(ui, ".oxfmtrc.json"), `--stdin-filepath=${target}`],
    { cwd: ui, encoding: "utf8", input: header + raw, maxBuffer: 64 << 20 },
  );
}

const args = process.argv.slice(2);
const check = args.includes("--check");
const outIndex = args.indexOf("--out");
const out = outIndex >= 0 ? path.resolve(args[outIndex + 1]) : path.join(ui, target);
const fresh = generate();

if (!check) {
  writeFileSync(out, fresh);
} else if (readFileSync(out, "utf8") !== fresh) {
  const expected = path.join(mkdtempSync(path.join(tmpdir(), "api-types-")), path.basename(out));
  writeFileSync(expected, fresh);
  spawnSync("git", ["--no-pager", "diff", "--no-index", "--", out, expected], { stdio: "inherit" });
  console.error(`${out} is out of date with ${spec}; run: cd ui && npm run api-types`);
  process.exit(1);
}
