import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";

const script = path.join(import.meta.dirname, "api-types.mjs");

function run(...args) {
  return spawnSync(process.execPath, [script, ...args], { encoding: "utf8" });
}

describe("api-types", () => {
  const dir = mkdtempSync(path.join(tmpdir(), "api-types-"));
  const out = path.join(dir, "api-types.generated.ts");
  execFileSync(process.execPath, [script, "--out", out]);
  const generated = readFileSync(out, "utf8");

  it("writes the generated header and root schema aliases", () => {
    expect(generated.startsWith("// Generated by npm run api-types")).toBe(true);
    expect(generated).toContain("export type AgentRow =");
  });

  it("passes the check on an exact copy", () => {
    expect(run("--check", "--out", out).status).toBe(0);
  });

  it("fails the check on a stale copy and names the fix", () => {
    const stale = path.join(dir, "stale.ts");
    writeFileSync(stale, generated.replace("export type AgentRow =", "export type AgentRowOld ="));
    const result = run("--check", "--out", stale);
    expect(result.status).not.toBe(0);
    expect(result.stdout + result.stderr).toContain("cd ui && npm run api-types");
  });
});
